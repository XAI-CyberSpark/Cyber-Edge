import assert from 'node:assert/strict';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import Page from '../src/components/pages/DeveloperDocsPage';
import docs from 'virtual:developer-docs';
import { documentHeadings, resolveDocLink, searchDocuments, updateSummaries } from '../src/domain/developerDocs';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const root = createRoot(document.getElementById('root')!);
const click = async (el: HTMLElement | null) => { assert.ok(el); await act(async () => { el.click(); }); };
const label = (name: string) => document.querySelector<HTMLElement>(`[aria-label="${name}"]`);
assert.equal(docs.pages.length, 24);
assert.ok(docs.pages.every(p => p.markdown.length > 0 && !p.source.includes('.env')));
assert.equal(resolveDocLink('../api/01_OpenAPI_Guide.md', 'docs/developer/README.md', docs.pages).href, '/docs?doc=api');
assert.equal(resolveDocLink('../../backend/main.py', 'docs/developer/README.md', docs.pages).reference, 'backend/main.py');
assert.ok(searchDocuments(docs.pages, 'expected_updated_at').some(r => r.page.slug === 'api'));
assert.deepEqual(searchDocuments(docs.pages, '不存在9876'), []);
assert.deepEqual(documentHeadings('# Title\n## 中文\n```sh\n# comment\n```\n## 中文').map(h => h.id), ['title','中文','中文-1']);
console.log('PASS actual allowlist, relative links, search including code, duplicate headings');
await act(async () => root.render(<Page />));
assert.equal(document.querySelector('h1')?.textContent, '概览');
const summary = updateSummaries(docs.pages.find(p => p.slug === 'updates')!.markdown);
assert.equal(summary.length, 1);
assert.equal(document.querySelectorAll('.docs-update-entry').length, 1);
assert.equal(document.querySelectorAll('.docs-update-copy li').length, 6);
assert.doesNotMatch(document.querySelector('.docs-update-copy h3')!.textContent!, /dev\./);
assert.match(document.querySelector('.docs-update-copy')!.textContent!, /待验收/);
const summaryLink = document.querySelector<HTMLAnchorElement>('.docs-update-copy h3 a')!;
await click(summaryLink);
assert.equal(window.location.search, '?doc=updates');
assert.ok(document.getElementById(summary[0].id));
const archive = document.querySelector<HTMLElement>('.docs-prose a[href="/docs?doc=development-log"]');
await click(archive);
assert.equal(document.querySelector('h1')?.textContent, 'OAKEgde Studio 产品变更记录');
assert.match(document.querySelector('.docs-prose')!.textContent!, /2\.8\.0-dev\.1/);
console.log('PASS weekly bullets, precise summary anchor and preserved development history');
await click(document.querySelector('.docs-sidebar a[href="/docs?doc=api"]'));
assert.match(document.querySelector('h1')!.textContent!, /API/);
assert.equal(window.location.search, '?doc=api');
assert.ok(document.querySelectorAll('.docs-toc a').length > 5);
let copied = '';
Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (value: string) => { copied = value; } } });
await click(label('复制代码'));
assert.equal(copied, 'curl --fail http://127.0.0.1:8000/v1/projects/');
Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('denied'); } } });
await click(label('复制代码'));
assert.match(document.querySelector('[role=status]')!.textContent!, /无法访问剪贴板/);
console.log('PASS article navigation, TOC, successful copy and denied clipboard feedback');
label('搜索文档')!.focus(); await click(label('搜索文档'));
assert.equal(document.activeElement?.getAttribute('aria-label'), '搜索文档内容');
await act(async () => { const input = label('搜索文档内容')!; Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value')!.set!.call(input, '不存在9876'); input.dispatchEvent(new window.Event('input',{bubbles:true})); });
assert.match(document.querySelector('[role=dialog]')!.textContent!, /没有找到相关文档/);
await act(async () => { document.dispatchEvent(new window.KeyboardEvent('keydown', {key:'Escape', bubbles:true})); });
assert.equal(document.querySelector('[role=dialog]'), null);
// Radix restores focus after the close/unmount task.
await act(async () => { await new Promise(resolve => setTimeout(resolve, 0)); });
assert.equal(document.activeElement?.getAttribute('aria-label'), '搜索文档');
await click(label('切换到深色'));
assert.equal(document.querySelector('.docs-site')?.getAttribute('data-theme'), 'dark');
await click(label('切换到浅色'));
await act(async () => { history.pushState({}, '', '/docs?doc=missing'); window.dispatchEvent(new window.PopStateEvent('popstate')); });
assert.equal(document.querySelector('h1')?.textContent, '未找到文档');
console.log('PASS search input/empty state/focus return, theme and invalid route');
await act(async () => root.unmount());
