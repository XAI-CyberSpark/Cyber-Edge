import assert from 'node:assert/strict';
import React, {act, useEffect} from 'react';
import {createRoot} from 'react-dom/client';
import {SiteAccessGate} from '../src/components/ui/SiteAccessGate';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT=true;
Object.defineProperty(document,'hidden',{get:()=>false,configurable:true});
let mounts=0, calls=0, good=false, authed=false, gateOff=false;
function Content(){useEffect(()=>{mounts++;},[]);return <button>项目内容</button>;}
globalThis.fetch=(async(url: string, options: any)=>{
 calls++;
 if(url.endsWith('/session')) return {ok:true,json:async()=>gateOff?({authenticated:true,expires_in:0,required:false}):({authenticated:authed,expires_in:28800,required:true})};
 assert.equal(options.credentials,'same-origin'); assert.ok(JSON.parse(options.body).key);
 return {ok:good,json:async()=>good?({authenticated:true,expires_in:28800}):({detail:'使用密钥不正确，请重新输入。'})};
}) as any;
const root=createRoot(document.getElementById('root')!);
const type=async(value:string)=>act(async()=>{const el=document.querySelector('input')!;Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype,'value')!.set!.call(el,value);el.dispatchEvent(new window.Event('input',{bubbles:true}));});
const submit=async()=>act(async()=>document.querySelector('form')!.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true})));
await act(async()=>root.render(<SiteAccessGate><Content/></SiteAccessGate>));
assert.ok(document.querySelector('[role="dialog"]'));assert.equal(mounts,0);assert.equal(calls,1);assert.equal(document.activeElement,document.querySelector('input'));
await act(async()=>document.activeElement!.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
assert.ok(document.querySelector('[role="dialog"]'));
console.log('PASS 1: Gate on, no session: focused modal after one probe; Escape does not bypass it; protected children have not mounted.');
await type('wrong-test-key');await submit();assert.equal(mounts,0);assert.match(document.querySelector('[role="alert"]')!.textContent!,/不正确/);
console.log('PASS 2: Wrong key stays locked with inline feedback.');
good=true;await type('correct-test-key');await submit();assert.equal(document.querySelector('[role="dialog"]'),null);assert.equal(mounts,1);
assert.equal(window.localStorage.getItem('correct-test-key'),null);
authed=true;
console.log('PASS 3: Verified response unlocks and mounts content.');
authed=false;await act(async()=>window.dispatchEvent(new window.Event('focus')));assert.ok(document.querySelector('[role="dialog"]'));assert.equal(mounts,1);
await type('correct-test-key');await submit();assert.equal(document.querySelector('[role="dialog"]'),null);assert.equal(mounts,1);
console.log('PASS 4: Expired server session reopens the gate without discarding the mounted workspace.');
await act(async()=>root.unmount());
mounts=0;calls=0;gateOff=true;
const offContainer=document.createElement('div');document.body.appendChild(offContainer);
const offRoot=createRoot(offContainer);
await act(async()=>offRoot.render(<SiteAccessGate><Content/></SiteAccessGate>));
assert.equal(document.querySelector('[role="dialog"]'),null);assert.equal(mounts,1);assert.equal(calls,1);
console.log('PASS 5: Gate off server-side (required:false): unlocks after one probe, no dialog, no login call.');
await act(async()=>offRoot.unmount());
